public class OccurenceReplaceWithNum {
    public static void main(String[] args) {

       int num=5;
       for(int i=1;i<=num;i++){
           System.out.print(i);
       }
       for(int j=num-1;j>=1;j--){
           System.out.print(j);
       }
    }
}
